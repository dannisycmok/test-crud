import path from "node:path";
import { fileURLToPath } from "node:url";
import dotenv from "dotenv";
import pg from "pg";
import bcrypt from "bcryptjs";

dotenv.config({
  path: path.join(path.dirname(fileURLToPath(import.meta.url)), ".env"),
});

const { Pool, types } = pg;

// Keep DATE values as YYYY-MM-DD strings and prices as numbers in JSON.
types.setTypeParser(1082, (value) => value);
types.setTypeParser(1700, (value) => Number(value));

/** @type {pg.Pool | null} */
let pool = null;

/**
 * Return the shared Postgres pool connected to Supabase.
 * @returns {pg.Pool}
 */
export function getPool() {
  if (pool) {
    return pool;
  }

  const connectionString = process.env.DATABASE_URL?.trim();
  if (!connectionString) {
    throw new Error(
      "DATABASE_URL is missing. Add the Supabase Postgres connection string to backend/.env."
    );
  }

  const isLocal = /localhost|127\.0\.0\.1/.test(connectionString);
  pool = new Pool({
    connectionString,
    ssl: isLocal ? undefined : { rejectUnauthorized: false },
    max: 10,
  });
  return pool;
}

/**
 * Run a SQL statement and return its rows.
 * @param {string} text
 * @param {unknown[]} [values]
 * @returns {Promise<object[]>}
 */
export async function query(text, values = []) {
  const result = await getPool().query(text, values);
  return result.rows;
}

/**
 * Run a SQL statement and return the first row.
 * @param {string} text
 * @param {unknown[]} [values]
 * @returns {Promise<object | null>}
 */
export async function queryOne(text, values = []) {
  const rows = await query(text, values);
  return rows[0] ?? null;
}

/**
 * Add a named column assignment with the next Postgres placeholder.
 * Column names are chosen by the route, never taken from the request.
 * @param {string[]} assignments
 * @param {unknown[]} values
 * @param {string} column
 * @param {unknown} value
 */
export function addAssignment(assignments, values, column, value) {
  if (!/^[a-z_]+$/.test(column)) {
    throw new Error(`Invalid column name: ${column}`);
  }
  values.push(value);
  assignments.push(`${column} = $${values.length}`);
}

/**
 * Create the tables and insert the sample catalog when the database is empty.
 */
export async function initDatabase() {
  const database = getPool();
  await database.query(`
    CREATE TABLE IF NOT EXISTS users (
      uid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      uname TEXT NOT NULL,
      email TEXT NOT NULL UNIQUE,
      password TEXT NOT NULL
    );

    CREATE TABLE IF NOT EXISTS products (
      pid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      pname TEXT NOT NULL,
      description TEXT NOT NULL DEFAULT '',
      price NUMERIC(12, 2) NOT NULL CHECK (price >= 0),
      qty INTEGER NOT NULL CHECK (qty >= 0)
    );

    CREATE TABLE IF NOT EXISTS orders (
      oid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      uid INTEGER NOT NULL REFERENCES users (uid) ON DELETE RESTRICT ON UPDATE RESTRICT,
      pid INTEGER NOT NULL REFERENCES products (pid) ON DELETE RESTRICT ON UPDATE RESTRICT,
      order_date DATE NOT NULL
    );

    CREATE INDEX IF NOT EXISTS idx_orders_uid ON orders (uid);
    CREATE INDEX IF NOT EXISTS idx_orders_pid ON orders (pid);
  `);
  await seedIfEmpty();
}

/**
 * Insert sample rows the first time the users table is empty.
 */
async function seedIfEmpty() {
  const existing = await queryOne("SELECT COUNT(*)::int AS count FROM users");
  if (Number(existing?.count) > 0) {
    return;
  }

  const passwordHash = bcrypt.hashSync("Passw0rd!", 10);
  const client = await getPool().connect();
  try {
    await client.query("BEGIN");
    const ada = await client.query(
      "INSERT INTO users (uname, email, password) VALUES ($1, $2, $3) RETURNING uid",
      ["Ada Lovelace", "ada@example.com", passwordHash]
    );
    const grace = await client.query(
      "INSERT INTO users (uname, email, password) VALUES ($1, $2, $3) RETURNING uid",
      ["Grace Hopper", "grace@example.com", passwordHash]
    );
    const alan = await client.query(
      "INSERT INTO users (uname, email, password) VALUES ($1, $2, $3) RETURNING uid",
      ["Alan Turing", "alan@example.com", passwordHash]
    );
    const notebook = await client.query(
      "INSERT INTO products (pname, description, price, qty) VALUES ($1, $2, $3, $4) RETURNING pid",
      ["Field notebook", "Hardcover dotted notebook, 192 pages.", 18.5, 40]
    );
    const keyboard = await client.query(
      "INSERT INTO products (pname, description, price, qty) VALUES ($1, $2, $3, $4) RETURNING pid",
      ["Mechanical keyboard", "Compact keyboard with tactile switches.", 129, 12]
    );
    const lamp = await client.query(
      "INSERT INTO products (pname, description, price, qty) VALUES ($1, $2, $3, $4) RETURNING pid",
      ["Desk lamp", "Dimmable LED lamp with a warm color range.", 46, 7]
    );

    const insertOrder =
      "INSERT INTO orders (uid, pid, order_date) VALUES ($1, $2, $3)";
    await client.query(insertOrder, [ada.rows[0].uid, keyboard.rows[0].pid, "2026-03-02"]);
    await client.query(insertOrder, [grace.rows[0].uid, notebook.rows[0].pid, "2026-03-18"]);
    await client.query(insertOrder, [alan.rows[0].uid, lamp.rows[0].pid, "2026-04-09"]);
    await client.query(insertOrder, [ada.rows[0].uid, lamp.rows[0].pid, "2026-05-21"]);
    await client.query("COMMIT");
  } catch (error) {
    await client.query("ROLLBACK");
    throw error;
  } finally {
    client.release();
  }
}
